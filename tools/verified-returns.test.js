"use strict";
const assert=require("node:assert/strict");
const {verifiedReturns}=require("./verified-returns");
const events=[{id:"d",type:"deposit",date:"2025-01-01",amount:1000},{id:"b",type:"buy",date:"2025-01-02",amount:800}];
const args={events,terminalCash:200,positionsValue:900,terminal:{date:"2026-01-01",value:1100},ledgerEvidence:{complete:true,verifiedOpening:true,verifiedEnding:true,tradeCoverage:true},valuations:[{date:"2025-01-01",value:1000,externalFlow:0},{date:"2026-01-01",value:1100,externalFlow:0}],navVerified:true};
const ok=verifiedReturns(args);
assert.equal(ok.ready,true);assert.ok(ok.xirr>0.09&&ok.xirr<0.11);assert.ok(Math.abs(ok.twr-0.1)<1e-9);
assert.equal(verifiedReturns({...args,ledgerEvidence:{complete:true}}).xirr,null);
assert.equal(verifiedReturns({...args,terminal:{date:"2026-01-01",value:1200}}).ready,false);
const noNav=verifiedReturns({...args,navVerified:false});assert.equal(noNav.ready,false);assert.equal(noNav.twr,null);
assert.ok(noNav.xirr!==null,"verified XIRR independent of TWR NAV availability");
const mismatch=verifiedReturns({...args,valuations:[{date:"2025-01-01",value:1000,externalFlow:0},{date:"2025-12-30",value:1100}]});
assert.equal(mismatch.twr,null);assert.equal(mismatch.ready,false);
const extraFlow=verifiedReturns({...args,valuations:[{date:"2025-01-01",value:1000,externalFlow:0},{date:"2026-01-01",value:1100,externalFlow:100}]});
assert.equal(extraFlow.twr,null);assert.equal(extraFlow.ready,false);
const duplicateNAV=verifiedReturns({...args,valuations:[...args.valuations,{date:"2026-01-01",value:1100,externalFlow:0}]});
assert.equal(duplicateNAV.ready,false);assert.equal(duplicateNAV.twr,null);
const missingFlow=verifiedReturns({...args,valuations:[args.valuations[0],{date:"2026-01-01",value:1100}]});
assert.equal(missingFlow.ready,false);assert.equal(missingFlow.twr,null,"missing NAV external flow is unverified");
const nullFlow=verifiedReturns({...args,valuations:[args.valuations[0],{date:"2026-01-01",value:1100,externalFlow:null}]});
assert.equal(nullFlow.ready,false);assert.equal(nullFlow.twr,null,"null NAV external flow cannot be inferred as zero");
const noEvidence=verifiedReturns({...args,ledgerEvidence:null});
assert.equal(noEvidence.ready,false);assert.equal(noEvidence.xirr,null);
assert.equal(verifiedReturns({...args,events:[null]}).ready,false);
assert.equal(verifiedReturns({...args,valuations:[null,{date:"2026-01-01",value:1100,externalFlow:0}]}).ready,false);
console.log("verified returns tests passed");
